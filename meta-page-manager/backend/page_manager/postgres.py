"""PostgreSQL persistence for the existing, checkpointed Page/Reel store.

Each owner has a separate schema. Only validated UUID-derived identifiers enter
search_path. SQLite remains supported by the original standalone application.

Connections come from one bounded pool per DSN. Every checkout re-establishes
the tenant search_path inside its transaction, and every checkin resets row
factory, autocommit and search_path so no state leaks between schemas. Long
lived advisory-lock leases must use their own raw connection, never the pool.
"""
import atexit
import asyncio
from contextlib import contextmanager
import os
import re
import sqlite3
import threading
import time

import psycopg
from psycopg.rows import dict_row

from psycopg_pool import ConnectionPool,PoolTimeout

_pools={}
_background_slots={}
_pools_guard=threading.Lock()


def pool_size():
    try:size=int(os.environ.get('PM_PG_POOL_SIZE','24'))
    except ValueError:size=24
    # enqueue_due holds a central checkout while opening a workspace one, so
    # a pool of one connection could deadlock; two is the safe minimum.
    return size if 2<=size<=50 else 24


def pool_timeout():
    try:timeout=float(os.environ.get('PM_PG_POOL_TIMEOUT','10'))
    except ValueError:timeout=10.
    return timeout if 0<timeout<=60 else 10.


def _reset(raw):
    raw.row_factory=dict_row
    if raw.autocommit:raw.autocommit=False
    raw.execute('RESET search_path')
    raw.commit()


def _pool(dsn):
    with _pools_guard:
        pool=_pools.get(dsn)
        if pool is None or pool.closed:
            size=pool_size()
            pool=ConnectionPool(dsn,min_size=0,max_size=size,timeout=pool_timeout(),open=True,reset=_reset,
                kwargs={'row_factory':dict_row,'connect_timeout':5,'prepare_threshold':None})
            _pools[dsn]=pool
            # Limit background checkouts, including nested ones, so synchronous
            # scheduler work on the event loop retains four available slots.
            _background_slots[dsn]=threading.BoundedSemaphore(size-(4 if size>=8 else 0))
        return pool,_background_slots[dsn]


@contextmanager
def pooled_connection(dsn):
    pool,slots=_pool(dsn)
    try:asyncio.get_running_loop();foreground=True
    except RuntimeError:foreground=False
    timeout=pool_timeout();acquired=False
    started=time.monotonic()
    if not foreground:
        acquired=slots.acquire(timeout=timeout)
        if not acquired:raise PoolTimeout('Background PostgreSQL capacity timed out')
    try:
        # Even an unexpected foreground-only burst must fail promptly instead
        # of parking health checks behind a ten-second pool wait.
        remaining=max(0.001,timeout-(time.monotonic()-started))
        with pool.connection(timeout=min(remaining,0.25) if foreground else remaining) as raw:
            raw.row_factory=dict_row
            yield raw
    finally:
        if acquired:slots.release()


def close_pools():
    with _pools_guard:
        pools=list(_pools.values());_pools.clear();_background_slots.clear()
    for pool in pools:pool.close()


atexit.register(close_pools)


class Row(dict):
    def __getitem__(self,key):
        return list(self.values())[key] if isinstance(key,int) else super().__getitem__(key)


class Cursor:
    def __init__(self,rows=(),rowcount=0,lastrowid=None):
        self.rows=iter(Row(row) for row in rows);self.rowcount=rowcount;self.lastrowid=lastrowid
    def fetchone(self):return next(self.rows,None)
    def fetchall(self):return list(self.rows)
    def __iter__(self):return self.rows


def translate(sql):
    sql=re.sub(r'INTEGER PRIMARY KEY AUTOINCREMENT','BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',sql,flags=re.I)
    sql=re.sub(r'\bINDEXED BY \w+','',sql,flags=re.I)
    sql=re.sub(r'\bCOLLATE NOCASE\b','',sql,flags=re.I)
    sql=re.sub(r'\bNOT p\.posts_has_more\b','p.posts_has_more=0',sql)
    sql=re.sub(r'\b(\w+(?:\.\w+)?) IS NOT (?!NULL\b)(\w+(?:\.\w+)?)',r'\1 IS DISTINCT FROM \2',sql)
    sql=re.sub(r"json_extract\(([^,]+),'\$\.([^']+)'\)",r"(\1::jsonb ->> '\2')",sql)
    sql=re.sub(r"json_type\(([^,]+),'\$\.([^']+)'\)",r"jsonb_typeof(\1::jsonb -> '\2')",sql)
    sql=re.sub(r"(->> 'finish_attempted'\))=1",r"\1='true'",sql)
    sql=re.sub(r'json_each\(([^()]+)\)',r"jsonb_array_elements_text(COALESCE(\1,'[]')::jsonb)",sql)
    # SQLite permits a JOIN table-function without ON; PostgreSQL uses LATERAL.
    sql=re.sub(r'JOIN (jsonb_array_elements_text\([^\n]+?::jsonb\)) j ON',r'JOIN LATERAL \1 j(value) ON',sql)
    sql=re.sub(r"SUM\((posts_today>0|status='working'|status IN \([^)]*\))\)",r'SUM((\1)::int)',sql)
    if 'sqlite_master' in sql:
        sql=sql.replace('sqlite_master',"information_schema.tables").replace("type='table'",'table_schema=current_schema()').replace('name=','table_name=')
    ignore=bool(re.search(r'INSERT OR IGNORE',sql,re.I))
    sql=re.sub('INSERT OR IGNORE','INSERT',sql,flags=re.I)
    if ignore:sql=sql.rstrip().rstrip(';')+' ON CONFLICT DO NOTHING'
    return sql.replace('?','%s')


class Database:
    def __init__(self,raw):self.raw=raw
    def create_function(self,*_,**__):pass
    def execute(self,sql,params=()):
        if sql.startswith('PRAGMA table_info('):
            table=re.fullmatch(r'PRAGMA table_info\((\w+)\)',sql)[1]
            rows=self.raw.execute('SELECT ordinal_position AS cid,column_name AS name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name=%s ORDER BY ordinal_position',(table,)).fetchall()
            return Cursor(rows)
        if sql.startswith('PRAGMA'):return Cursor()
        if sql=='BEGIN IMMEDIATE':
            self.raw.execute('SELECT pg_advisory_xact_lock(hashtext(current_schema()))')
            return Cursor()
        sql=translate(sql)
        serial=bool(re.match(r'INSERT INTO (connections|reel_jobs|events)\b',sql,re.I)) and 'RETURNING' not in sql.upper()
        if serial:sql+=' RETURNING id'
        try:
            cursor=self.raw.execute(sql,tuple(params))
        except psycopg.IntegrityError as error:
            raise sqlite3.IntegrityError('PostgreSQL constraint conflict') from error
        rows=cursor.fetchall() if cursor.description else []
        return Cursor(rows,cursor.rowcount,rows[0]['id'] if serial and rows else None)
    def executemany(self,sql,rows):
        rows=[tuple(row) for row in rows]
        if not rows:return Cursor()
        try:
            with self.raw.cursor() as cursor:
                cursor.executemany(translate(sql),rows)
                return Cursor((),cursor.rowcount)
        except psycopg.IntegrityError as error:
            raise sqlite3.IntegrityError('PostgreSQL constraint conflict') from error
    def executescript(self,sql):
        for statement in sql.split(';'):
            if statement.strip():self.execute(statement.strip())


@contextmanager
def connection(dsn,namespace):
    if not isinstance(namespace,str) or not re.fullmatch(r'w_[a-f0-9]{32}',namespace):
        raise ValueError('Invalid workspace namespace')
    with pooled_connection(dsn) as raw:
        raw.execute(f'CREATE SCHEMA IF NOT EXISTS "{namespace}"')
        raw.execute(f'SET LOCAL search_path TO "{namespace}"')
        yield Database(raw)


def prepare(dsn,namespace):
    with connection(dsn,namespace) as db:
        db.raw.execute('''CREATE OR REPLACE FUNCTION julianday(text) RETURNS numeric LANGUAGE sql IMMUTABLE AS $$ SELECT extract(epoch FROM NULLIF($1,'')::timestamptz)/86400 $$''')
        db.raw.execute('''CREATE OR REPLACE FUNCTION casefold(text) RETURNS text LANGUAGE sql IMMUTABLE AS $$ SELECT replace(replace(lower($1),'ß','ss'),'ς','σ') $$''')
        db.raw.execute('''CREATE OR REPLACE FUNCTION fold_text(text) RETURNS text LANGUAGE sql IMMUTABLE AS $$ SELECT casefold(coalesce($1,'')) $$''')
        db.raw.execute('''CREATE OR REPLACE FUNCTION instr(text,text) RETURNS integer LANGUAGE sql IMMUTABLE AS $$ SELECT position($2 IN $1) $$''')
        db.raw.execute('''CREATE OR REPLACE FUNCTION reel_local_date(text,text) RETURNS text LANGUAGE sql STABLE AS $$ SELECT to_char($1::timestamptz AT TIME ZONE $2,'YYYY-MM-DD') $$''')
